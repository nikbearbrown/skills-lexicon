"""List every claim a checking model contradicted, for a person to settle.

    python3 -I scripts/review_flags.py [docs/REVIEW-FLAGS.md]

Reads the `checked` evidence with outcome `contradicts`, from reviewers and second drafts, and writes a Markdown list grouped by
class, each with who said it (model and effort from data/runs.json) and the note. A contradiction is not a verdict: the
reviewer may be the one who is wrong. It only says where a person should look first, and it blocks `reviewed` until settled.
"""
import collections
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "tools"))
import lexicon as L  # noqa: E402


def main(out="docs/REVIEW-FLAGS.md"):
    entries, _ = L.load()
    runs = L.load_runs()
    by = collections.defaultdict(list)
    for e in entries:
        for ev in e.get("evidence", []):
            if ev["action"] == "checked" and ev.get("outcome") == "contradicts" and ev["by"].startswith("model:"):
                r = runs.get(ev.get("run"), {})
                by[L.top_class(e)].append((e["preferred_name"], e["key"], ev["field"], ev.get("note", ""), f"{r.get('model', ev['by'][6:])} ({r.get('effort', '?')})"))
    n = sum(len(v) for v in by.values())
    lines = ["# Claims a checking model contradicted", "",
             f"{n} records on {len({k for v in by.values() for _, k, *_ in v})} entries. A contradiction is not a verdict: the checker may be the one who is wrong. "
             "It says where a person should look first, and it blocks `reviewed` until someone settles it. Generated by `scripts/review_flags.py`.", ""]
    for cls in ("certification", "language", "ability", "skill"):
        if not by[cls]:
            continue
        lines += [f"## {cls.capitalize()} ({len(by[cls])})", ""]
        for name, key, field, note, who in sorted(by[cls], key=lambda x: (x[0].casefold(), x[2])):
            f = field if not field.startswith("variant:") else "variant " + field[8:]
            f = f if not f.startswith("relation:") else "relation"
            lines.append(f"- **{name}** (`{key}`) · {f} · {who}: {note or 'no note'}")
        lines.append("")
    Path(out).write_text("\n".join(lines).rstrip() + "\n", "utf-8")
    print(f"{n} contradicting records written to {out}")


if __name__ == "__main__":
    main(*sys.argv[1:2])
